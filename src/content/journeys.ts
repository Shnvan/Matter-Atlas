type StepInput = [string, string, string[], EdgeType];
const journey = (
  id: string,
  title: string,
  summary: string,
  rows: StepInput[],
): SignalJourney => {
  const steps = rows.map(([title, text, componentRefs, edgeType], i) => ({
    id: `${id}-${i}`,
    title,
    text,
    componentRefs,
    edgeType,
    sourceRefs: [
      "SRC-001",
      "SRC-002",
      "SRC-006",
      "SRC-019",
      "SRC-020",
      "SRC-027",
      "SRC-033",
    ],
    claims: {
      event: c(
        text,
        [
          "SRC-001",
          "SRC-002",
          "SRC-006",
          "SRC-019",
          "SRC-020",
          "SRC-027",
          "SRC-033",
        ],
        "UNO-TH_Rev3e connectivity; general firmware and carrier mechanisms",
      ),
    },
  }));
  return {
    id,
    title,
    summary,
    startingEvent: steps[0].text,
    finalResult: steps.at(-1)!.text,
    steps,
    edges: steps
      .slice(1)
      .map((s, i) => ({
        fromStepId: steps[i].id,
        toStepId: s.id,
        type: s.edgeType,
        explanation: s.text,
      })),
    sourceRefs: [
      "SRC-001",
      "SRC-002",
      "SRC-006",
      "SRC-019",
      "SRC-020",
      "SRC-027",
      "SRC-033",
    ],
    applicability: "UNO-TH_Rev3e reference design",
    representation: "simplified",
  };
};
